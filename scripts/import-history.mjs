// Regenerates src/data/history.ts from the core repository's timeline source:
//   node scripts/import-history.mjs ../RoboLang/docs/development-steps.html src/data/history.ts
// Then set roadmapSnapshot.historyCommit in facts.ts to the core commit it was read from.
import { readFileSync, writeFileSync } from 'node:fs';
const html = readFileSync(process.argv[2], 'utf8');
const m = html.match(/const steps = (\[[\s\S]*?\n\]);/);
const steps = Function(`return ${m[1]}`)();
const area = { lang: 'Language', exec: 'Simulation', core: 'Core / interop', bench: 'AI benchmark', ros: 'Physics / hardware', gov: 'Governance' };
const rows = [];
for (const [date, cards, next] of steps) {
  if (next) continue;
  for (const [n, title, tag, , text, kind] of cards) rows.push({ step: n, date, title, tag, text, area: area[kind] });
}
const out = `// The development history shown on the roadmap page, steps 0 to ${rows.at(-1).step}.
// Generated by scripts/import-history.mjs from docs/development-steps.html in the core repository (the source of
// docs/development-steps.png) at the commit in roadmapSnapshot.historyCommit. Regenerate
// rather than editing by hand, so the site and the core repository's timeline agree.

export interface HistoryStep {
  step: number;
  date: string;
  title: string;
  tag: string;
  text: string;
  area: string;
}

export const history: HistoryStep[] = ${JSON.stringify(rows, null, 2)};
`;
writeFileSync(process.argv[3], out);
console.log(rows.length, 'rows');
